def main():
    print(f"Начинаю импорт {len(EXERCISES)} упражнений...")
    imported = 0
    for ex in EXERCISES:
        muscle_group = ex["primary_muscles"][0] if ex["primary_muscles"] else "full_body"
        pattern = ex.get("movement_pattern", "")
        if "stretch" in pattern or "mobility" in pattern:
            ex_type = "stretching"
        elif pattern in ("run", "cycle", "walk", "swim", "elliptical", "row", "jump", "boxing"):
            ex_type = "cardio"
        else:
            ex_type = "strength"

        description = json.dumps({
            "movement_pattern": ex.get("movement_pattern"),
            "difficulty": ex.get("difficulty"),
            "progression_to": ex.get("progression_to"),
            "regression_to": ex.get("regression_to"),
            "contraindications": ex.get("contraindications"),
            "secondary_muscles": ex.get("secondary_muscles"),
        }, ensure_ascii=False)

        add_exercise(
            name=ex["name_ru"],
            muscle_group=muscle_group,
            ex_type=ex_type,
            equipment=ex.get("equipment", "bodyweight"),
            description=description,
            is_custom=False,
        )
        imported += 1

    print(f"Импортировано {imported} упражнений. Готово!")

if __name__ == "__main__":
    main()