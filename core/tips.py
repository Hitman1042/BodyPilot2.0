def _slot_number(day: date) -> int:
    iso = day.isocalendar()
    slot = 0 if day.weekday() == 1 else 1
    return iso.year * 106 + iso.week * 2 + slot


def _tip_index(user_id: int, slot: int) -> int:
    digest = hashlib.sha256(f"{user_id}:{slot}".encode()).hexdigest()
    return int(digest[:12], 16) % len(_ALL_TIPS)


def select_tip(user_id: int, tip_date: Optional[date] = None) -> Dict[str, Any]:
    """Детерминированно выбрать совет; соседние отправки не повторяются."""
    if tip_date is None:
        user = get_user(user_id) or {}
        offset = int(user.get("timezone_offset") or 0)
        tip_date = (datetime.now(timezone.utc) + timedelta(minutes=offset)).date()
    slot = _slot_number(tip_date)
    index = _tip_index(user_id, slot)
    if index == _tip_index(user_id, slot - 1):
        index = (index + 1) % len(_ALL_TIPS)
    tip = _ALL_TIPS[index].copy()
    tip["index"] = index
    return tip


def build_daily_tip(user_id: int, tip_date: Optional[date] = None) -> str:
    """Собрать персонализированный текст совета без вызова AI."""
    user = get_user(user_id)
    if not user:
        raise ValueError("Пользователь не найден")

    tip = select_tip(user_id, tip_date)
    plan = get_nutrition_plan(user_id)
    protein_target = round(float((plan.get("macros") or {}).get("protein_g") or 120))
    water_ml = get_water_target(user_id)
    body = tip["text"].format(
        protein_g=protein_target,
        water_ml=water_ml,
        water_l=water_ml / 1000,
        calories=round(float(plan.get("target_calories") or 2000)),
    )

    sport = get_user_sport(user_id) or {}
    if sport.get("name") and tip["topic"] in ("workouts", "recovery"):
        body += f" Для направления «{sport['name']}» это особенно полезно."

    goal = user.get("goal", "maintain")
    lead = _GOAL_LEADS.get(goal, _GOAL_LEADS["maintain"])
    return f"💡 Совет дня:\n{lead}\n{body}\n\n{_CTAS[tip['topic']]}"
